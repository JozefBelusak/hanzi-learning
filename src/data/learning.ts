import type { LearningActivity, LearningQuestion } from '../types/learning'

function choice(
  id: string,
  prompt: string,
  options: [string, string, string?][],
  answer: string,
  explanation: string,
  extra: { hint?: string; audioText?: string } = {},
): LearningQuestion {
  return {
    id, type: 'choice', prompt,
    options: options.map(([optionId, text, pinyin]) => ({ id: optionId, text, ...(pinyin ? { pinyin } : {}) })),
    answer, explanation, ...extra,
  }
}

function order(
  id: string,
  prompt: string,
  tokens: string[],
  explanation: string,
  extra: { hint?: string; audioText?: string; acceptedOrders?: string[][] } = {},
): LearningQuestion {
  const { acceptedOrders = [tokens], ...rest } = extra
  return { id, type: 'order', prompt, tokens, acceptedOrders, explanation, ...rest }
}

