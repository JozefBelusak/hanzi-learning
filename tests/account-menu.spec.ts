import { test, expect } from './fixtures'

for (const role of ['student', 'lecturer', 'admin'] as const) {
  test.describe(`${role} account panel`, () => {
    test.use({ account: role })
    test('keeps account links behind one header control and respects role permissions', async ({ page }) => {
      await page.goto('/#/home')
      const trigger = page.getByRole('button', { name: 'Your account', exact: true })
      await expect(trigger).toHaveAttribute('aria-expanded', 'false')
      await expect(page.getByRole('button', { name: 'Sign out', exact: true })).toHaveCount(0)
      await trigger.focus()
      await page.keyboard.press('Enter')
      const panel = page.getByRole('dialog', { name: 'Your account', exact: true })
      await expect(panel).toBeVisible()
      await expect(panel.getByRole('button', { name: 'Close account panel', exact: true })).toBeFocused()
      await expect(panel.locator('.account-role')).toHaveText(role === 'student' ? 'Student' : role === 'lecturer' ? 'Lecturer' : 'Admin')
      await expect(panel.getByRole('button', { name: 'Lecturer workspace', exact: true })).toHaveCount(role === 'student' ? 0 : 1)
      await expect(panel.getByRole('button', { name: 'Administration', exact: true })).toHaveCount(role === 'admin' ? 1 : 0)
      await page.keyboard.press('Escape')
      await expect(panel).toHaveCount(0)
      await expect(trigger).toBeFocused()
      await trigger.click()
      await page.getByRole('heading', { name: 'Home', exact: true }).click()
      await expect(panel).toHaveCount(0)
      await trigger.click()
      await panel.getByRole('button', { name: 'Sign out', exact: true }).focus()
      await page.keyboard.press('Tab')
      await expect(panel).toHaveCount(0)
      await trigger.click()
      await panel.getByRole('button', { name: 'Public lessons', exact: true }).click()
      await expect(page).toHaveURL(/#\/lessons$/)
      await expect(panel).toHaveCount(0)
      await expect(page.getByRole('navigation', { name: 'Main navigation', exact: true })).toBeVisible()
    })
  })
}

for (const width of [320, 360, 640, 768, 1280]) {
  test.describe(`${width}px header and filters`, () => {
    test.use({ account: 'lecturer' })
    test('fits long names, keyboard filters and the expanded account panel', async ({ page, backend }) => {
      backend.users.find((user) => user.role === 'lecturer')!.display_name = 'Lecturer'.repeat(10)
      await page.setViewportSize({ width, height: 850 })
      await page.goto('/#/exercises')
      const filters = page.getByRole('group', { name: 'Content level and difficulty', exact: true })
      await expect(filters.getByRole('combobox')).toHaveCount(0)
      await filters.getByRole('radio', { name: 'All levels', exact: true }).focus()
      await page.keyboard.press('ArrowRight')
      await expect(filters.getByRole('radio', { name: 'Beginner', exact: true })).toBeChecked()
      await filters.getByRole('radio', { name: 'Challenging', exact: true }).check()
      await expect(page.getByRole('heading', { name: 'No exercises found', exact: true })).toBeVisible()
      await filters.getByRole('radio', { name: 'All difficulties', exact: true }).check()
      await expect(page.locator('.exercise-card')).toHaveCount(3)
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await page.screenshot({ path: `playwright-report/ui-filters-${width}.png`, fullPage: true, animations: 'disabled' })
      await page.getByRole('button', { name: 'Your account', exact: true }).click()
      const panel = page.getByRole('dialog', { name: 'Your account', exact: true })
      const bounds = await panel.boundingBox()
      expect(bounds!.x).toBeGreaterThanOrEqual(0)
      expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(width)
      expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(850)
      await page.screenshot({ path: `playwright-report/ui-account-${width}.png`, fullPage: true, animations: 'disabled' })
      await panel.getByRole('button', { name: 'Lecturer workspace', exact: true }).click()
      await expect(page.getByRole('heading', { name: 'Lecturer workspace', exact: true })).toBeVisible()
      await expect(panel).toHaveCount(0)
    })
  })
}
