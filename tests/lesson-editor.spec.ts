async function chooseWord(block: Locator, query: string, hanzi: string) {
  await block.getByRole('searchbox', { name: 'Search vocabulary', exact: true }).fill(query)
  await block.getByRole('checkbox', { name: new RegExp(`^${hanzi} ·`) }).check()
}

