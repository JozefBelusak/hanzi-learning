test('keeps incomplete drafts and unsaved input after validation or network failure', async ({ page, backend }) => {
  await page.goto('/#/teach')
  await page.getByRole('button', { name: 'New lesson', exact: true }).click()
  await page.getByLabel('Title', { exact: true }).fill('An unfinished lesson')
  await page.getByRole('button', { name: 'Add chinese example block', exact: true }).click()
  await page.getByLabel('Chinese characters', { exact: true }).fill('你好')
  await page.getByLabel('Publish to all signed-in learners', { exact: true }).check()
  await page.getByRole('button', { name: 'Save lesson', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Block 1')
  expect(backend.lessons).toHaveLength(0)
  await page.getByLabel('Publish to all signed-in learners', { exact: true }).uncheck()
  backend.setLessonSaveFailure(true)
  await page.getByRole('button', { name: 'Save lesson', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('could not be completed')
  await expect(page.getByLabel('Chinese characters', { exact: true })).toHaveValue('你好')
  backend.setLessonSaveFailure(false)
  await page.getByRole('button', { name: 'Save lesson', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Lesson saved.')
  await page.reload()
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await expect(page.getByLabel('Chinese characters', { exact: true })).toHaveValue('你好')
  await expect(page.getByLabel('Pinyin', { exact: true })).toHaveValue('')
})

test('opens legacy text safely and converts it only when its author saves', async ({ page, backend }) => {
  const content = '你好\n<script>window.pwned = true</script>'
  const legacy = { id: '10000000-0000-4000-8000-000000000001', source: 'lecturer' as const, author_id: backend.users[1].id, title: 'Original lesson', summary: '', content, published: true, languageLevel: 'beginner' as const, difficulty: 'balanced' as const, created_at: '2026-11-03T10:00:00Z', updated_at: '2026-11-03T10:00:00Z' }
  backend.lessons.push(legacy, { ...legacy, id: '10000000-0000-4000-8000-000000000002', author_id: backend.users[2].id, title: 'Another author' })
  await page.goto('/#/teach')
  await expect(page.getByText('Another author', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await expect(page.getByLabel('Explanation text', { exact: true })).toHaveValue(content)
  expect(backend.requests.filter((request) => ['POST', 'PATCH'].includes(request.method) && request.path.endsWith('/public_lessons'))).toHaveLength(0)
  await page.getByRole('button', { name: 'Preview lesson', exact: true }).click()
  await expect(page.locator('.lesson-prose')).toContainText('<script>window.pwned = true</script>')
  expect(await page.evaluate(() => 'pwned' in window)).toBe(false)
  await page.getByRole('button', { name: 'Edit blocks', exact: true }).click()
  await page.getByRole('button', { name: 'Save lesson', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Lesson saved.')
  expect(backend.lessons).toHaveLength(2)
  expect(backend.lessons[0]).toMatchObject({ id: legacy.id, author_id: legacy.author_id, content })
})

