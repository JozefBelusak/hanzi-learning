import { test, expect, accountStudyKey, completeOnboarding } from './fixtures'
import type { Page } from '@playwright/test'

test.use({ account: null })
async function login(page: Page, email = 'student@example.test') {
  await page.goto('/#/login')
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Password', { exact: true }).fill('Correct-password-123')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
}

test('requires onboarding for existing incomplete accounts, resists direct links and restores the requested practice after saving', async ({ page, backend }) => {
  backend.needsOnboarding()
  await page.goto('/#/practice/food/flashcards')
  await expect(page).toHaveURL(/#\/login$/)
  await page.getByLabel('Email', { exact: true }).fill('student@example.test')
  await page.getByLabel('Password', { exact: true }).fill('Correct-password-123')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(/#\/onboarding$/)
  await expect(page.getByRole('heading', { name: 'Make Hanzi your own' })).toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Main navigation' })).toHaveCount(0)
  await page.goto('/#/course')
  await expect(page).toHaveURL(/#\/onboarding$/)
  await page.reload()
  await expect(page).toHaveURL(/#\/onboarding$/)
  await page.goto('/#/practice/food/flashcards')
  await expect(page).toHaveURL(/#\/onboarding$/)
  await page.getByLabel('What should we call you?', { exact: true }).fill('Jozef')
  await page.getByLabel('Chinese language level', { exact: true }).selectOption('elementary')
  await page.getByLabel('Preferred difficulty', { exact: true }).selectOption('gentle')
  await page.getByLabel('Speaking', { exact: true }).check()
  await page.getByLabel('Travel', { exact: true }).check()
  await page.getByLabel('Daily goal · attempts', { exact: true }).fill('7')
  // A focus refresh must not discard an unfinished form.
  const before = backend.requests.filter((request) => request.path === '/rest/v1/profiles').length
  await page.evaluate(() => window.dispatchEvent(new Event('focus')))
  await expect.poll(() => backend.requests.filter((request) => request.path === '/rest/v1/profiles').length).toBeGreaterThan(before)
  await expect(page.getByLabel('What should we call you?', { exact: true })).toHaveValue('Jozef')
  await page.getByRole('button', { name: 'Finish setup', exact: true }).click()
  await expect(page).toHaveURL(/#\/practice\/food\/flashcards$/)
  expect(backend.users[0]).toMatchObject({ display_name: 'Jozef', language_level: 'elementary', difficulty: 'gentle', preferred_modes: ['speech'], learning_goals: ['travel'], daily_goal: 7 })
  const request = backend.requests.find((item) => item.path === '/rest/v1/rpc/save_learning_profile')!
  expect(Object.keys(request.body).sort()).toEqual(['profile_daily_goal', 'profile_difficulty', 'profile_goals', 'profile_level', 'profile_modes', 'profile_name'])
  await page.getByRole('button', { name: 'Show answer', exact: true }).click()
  await page.getByRole('button', { name: 'Good', exact: true }).click()
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name: 'Home', exact: true }).click()
  await expect(page.getByRole('region', { name: "Today's practice" })).toContainText('1 / 7 practice attempts')
  await expect(page.getByRole('region', { name: 'Your learning plan' })).toContainText('Travel')
  await page.getByRole('button', { name: 'Practise speaking', exact: true }).click()
  await expect(page).toHaveURL(/#\/practice\/all\/speech$/)
})

test('validates required selections and keeps learning locked when the profile save fails', async ({ page, backend }) => {
  backend.needsOnboarding()
  await login(page)
  await expect(page).toHaveURL(/#\/onboarding$/)
  await page.getByRole('button', { name: 'Finish setup', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Choose at least one')
  expect(backend.requests.filter((item) => item.path === '/rest/v1/rpc/save_learning_profile')).toHaveLength(0)
  backend.setSaveFailure(true)
  await completeOnboarding(page)
  await expect(page.getByRole('alert')).toContainText('could not be saved')
  expect(backend.users[0].onboarding_completed_at).toBeNull()
  await expect(page).toHaveURL(/#\/onboarding$/)
  await expect(page.getByRole('navigation', { name: 'Main navigation' })).toHaveCount(0)
  backend.setSaveFailure(false)
  await page.getByRole('button', { name: 'Finish setup', exact: true }).click()
  await expect(page).toHaveURL(/#\/home$/)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Home', exact: true })).toBeVisible()
  await page.goto('/#/onboarding')
  await expect(page).toHaveURL(/#\/home$/)
})

test('later profile edits persist in the database, update daily progress and preserve attempts', async ({ page, backend }) => {
  await login(page)
  await page.goto('/#/practice/food/flashcards')
  await page.getByRole('button', { name: 'Show answer', exact: true }).click()
  await page.getByRole('button', { name: 'Good', exact: true }).click()
  await expect.poll(() => page.evaluate((key) => JSON.parse(localStorage.getItem(key) ?? '{}').attempts?.length, accountStudyKey)).toBe(1)
  const completed = backend.users[0].onboarding_completed_at
  await page.goto('/#/settings')
  await page.getByLabel('What should we call you?', { exact: true }).fill('Updated learner')
  await page.getByLabel('Chinese language level', { exact: true }).selectOption('intermediate')
  await page.getByLabel('Preferred difficulty', { exact: true }).selectOption('challenging')
  await page.getByLabel('Daily goal · attempts', { exact: true }).fill('3')
  await page.getByLabel('Writing characters', { exact: true }).check()
  await page.getByLabel('Study and exams', { exact: true }).check()
  await page.getByRole('button', { name: 'Save preferences', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Preferences saved to your account.')
  expect(backend.users[0]).toMatchObject({ display_name: 'Updated learner', language_level: 'intermediate', difficulty: 'challenging', daily_goal: 3, onboarding_completed_at: completed })
  await page.reload()
  await expect(page.getByLabel('Daily goal · attempts', { exact: true })).toHaveValue('3')
  await expect(page.getByLabel('Writing characters', { exact: true })).toBeChecked()
  await page.goto('/#/progress')
  await expect(page.getByRole('region', { name: 'Your learning plan' })).toContainText('Intermediate · Challenging difficulty · 3 attempts a day')
  await expect(page.getByRole('region', { name: "Today's practice" })).toContainText('1 / 3')
  await expect(page.locator('.stat-card').filter({ hasText: 'Total attempts' })).toContainText('1')
  // Even an empty device cache cannot replace the database profile with local defaults.
  await page.evaluate((key) => localStorage.removeItem(key), accountStudyKey)
  await page.reload()
  await expect(page.getByRole('region', { name: 'Your learning plan' })).toContainText('3 attempts a day')
  await page.getByRole('button', { name: 'Edit profile', exact: true }).click()
  await expect(page.getByLabel('What should we call you?', { exact: true })).toHaveValue('Updated learner')
})

for (const role of ['lecturer', 'admin'] as const) {
  test(`${role} completes onboarding before entering their workspace`, async ({ page, backend }) => {
    backend.needsOnboarding(`${role}@example.test`)
    await login(page, `${role}@example.test`)
    await expect(page).toHaveURL(/#\/onboarding$/)
    await completeOnboarding(page)
    await expect(page).toHaveURL(role === 'admin' ? /#\/admin$/ : /#\/teach$/)
  })
}

test('allows sign-out from onboarding and guards it for unauthenticated visitors', async ({ page, backend }) => {
  backend.needsOnboarding()
  await login(page)
  await expect(page).toHaveURL(/#\/onboarding$/)
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page).toHaveURL(/#\/login$/)
  await page.goBack()
  await expect(page.getByRole('navigation', { name: 'Main navigation' })).toHaveCount(0)
  await page.goto('/#/onboarding')
  await expect(page).toHaveURL(/#\/login$/)
  await expect(page.getByRole('button', { name: 'Finish setup', exact: true })).toHaveCount(0)
})

for (const width of [360, 1280]) {
  test(`${width}px: onboarding fits the viewport and keyboard selections work`, async ({ page, backend }) => {
    backend.needsOnboarding()
    await page.setViewportSize({ width, height: 850 })
    await login(page)
    await expect(page).toHaveURL(/#\/onboarding$/)
    const speaking = page.getByLabel('Speaking', { exact: true })
    await speaking.focus()
    await page.keyboard.press('Space')
    await expect(speaking).toBeChecked()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `playwright-report/onboarding-${width}.png`, fullPage: true })
    await page.getByLabel('Travel', { exact: true }).check()
    await page.getByRole('button', { name: 'Finish setup', exact: true }).click()
    await expect(page).toHaveURL(/#\/home$/)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  })
}
